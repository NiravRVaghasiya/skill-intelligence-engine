"""Reproduce the vocabulary-collision failure documented in ml-ai-skills docs/ROUTING.md.

The documented output ("computer-vision" as #1 for a fraud-detection task, via the shared
word "detection") was observed on the corpus at commit c54f548, where router.py was
introduced. The source repo's later capability-tag audit changed the keyword router's
answer, so both corpora are run: the historical one (extracted read-only with
`git archive`) and HEAD (the vendored data/skills). Each system is scored on the same
corpus it would have seen.

Usage:
    python -m eval.collision --source ../ml-ai-skills
"""
from __future__ import annotations
import argparse
import io
import json
import subprocess
import tarfile
import tempfile
from pathlib import Path

from sie.router import HybridRouter
from eval.baseline import KeywordBaseline
from eval.report import replace_block

QUERY = "Build a fraud detection model and evaluate it under severe class imbalance"
HISTORICAL_REV = "c54f548"
# Correct = the in-domain skills for "build a classifier + evaluate under imbalance";
# wrong = computer-vision, which only shares the word "detection" ("object detection").
CORRECT = {"model-evaluation", "supervised-learning"}
OUT = Path("benchmarks")


def extract_rev(source: Path, rev: str, dest: Path) -> str:
    """`git archive` a revision into dest (never touches the source working tree)."""
    commit = subprocess.run(["git", "-C", str(source), "rev-parse", "--short", rev],
                            capture_output=True, text=True, check=True).stdout.strip()
    tar = subprocess.run(["git", "-C", str(source), "archive", rev], capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as tf:
        if hasattr(tarfile, "data_filter"):      # Python >= 3.11.4 / 3.12
            tf.extractall(dest, filter="data")
        else:  # pragma: no cover
            tf.extractall(dest)
    return commit


def keyword_run(skills_dir: Path, scripts_dir: Path) -> dict:
    """route() exactly as shipped (what `python scripts/router.py` prints)."""
    b = KeywordBaseline(skills_dir, scripts_dir=scripts_dir, shipped=True)
    hits = b.retrieve(QUERY, k=10)
    return {"intent": b.intent(QUERY),
            "route": [{"slug": h.skill_slug, "score": h.score, "reasons": h.snippet} for h in hits]}


def sie_run(skills_dir: Path, persist_dir: Path, build: bool) -> dict:
    r = HybridRouter(skills_dir=str(skills_dir), persist_dir=str(persist_dir))
    if build:
        r.build()
    hits = r.retrieve(QUERY, k=5)
    return {"ranking": "cross-encoder" if r.reranker else "rrf (no reranker weights)",
            "route": [{"slug": h.skill_slug, "score": round(h.score, 4), "section": h.section} for h in hits]}


def _release_chroma() -> None:
    """Drop chromadb's cached per-path clients so their sqlite/HNSW files close."""
    import gc
    from chromadb.api.client import SharedSystemClient
    SharedSystemClient.clear_system_cache()
    gc.collect()


def _scored_top1(route: list[dict]) -> str:
    """Top keyword hit by score (route() may prepend 0-score prerequisites)."""
    return max(route, key=lambda h: h["score"])["slug"]


def _fmt_keyword(run: dict) -> str:
    lines = [f"intent: {run['intent']}"]
    lines += [f"  {h['slug']:24s} score={h['score']:<5.1f} {h['reasons']}" for h in run["route"]]
    return "\n".join(lines)


def _fmt_sie(run: dict) -> str:
    lines = [f"ranking: {run['ranking']}"]
    lines += [f"  {i}. {h['slug']:24s} score={h['score']:.4f} [{h['section']}]"
              for i, h in enumerate(run["route"], 1)]
    return "\n".join(lines)


def _verdict(slug: str) -> str:
    return "correct" if slug in CORRECT else "**wrong**"


def _correct_in_top3(route: list[dict], by_score: bool) -> str:
    """How many of the CORRECT skills a consumer sees in the first three results."""
    hits = sorted(route, key=lambda h: -h["score"]) if by_score else route
    found = [h["slug"] for h in hits[:3] if h["slug"] in CORRECT]
    return f"{len(found)}/{len(CORRECT)}" + (f" (`{'`, `'.join(found)}`)" if found else "")


def render(runs: dict) -> str:
    parts = [
        f"_Generated by `python -m eval.collision`; do not edit by hand._",
        f"**Query:** `{QUERY}`  \n**Correct:** any of `{'`, `'.join(sorted(CORRECT))}` "
        f"(build a classifier, evaluate it under imbalance). `computer-vision` only shares the word "
        f"\"detection\" (object detection).",
    ]
    for key, title in (("historical", f"Historical corpus — ml-ai-skills@{runs['historical']['commit']} "
                                      f"({runs['historical']['n_skills']} skills; the documented failure)"),
                       ("head", f"Current corpus — data/skills ({runs['head']['n_skills']} skills, "
                                f"after the source repo's capability-tag audit)")):
        run = runs[key]
        kw_top = _scored_top1(run["keyword"]["route"])
        sie_top = run["sie"]["route"][0]["slug"]
        parts += [f"#### {title}",
                  f"- Keyword router top-1 (by score): `{kw_top}` ({_verdict(kw_top)}); correct skills "
                  f"in its top-3: {_correct_in_top3(run['keyword']['route'], by_score=True)}\n"
                  f"- SIE top-1: `{sie_top}` ({_verdict(sie_top)}); correct skills in its top-3: "
                  f"{_correct_in_top3(run['sie']['route'], by_score=False)}",
                  "Keyword router (`route()` as shipped, verbatim source code):",
                  f"```text\n{_fmt_keyword(run['keyword'])}\n```",
                  "SIE (`HybridRouter.retrieve`, same corpus):",
                  f"```text\n{_fmt_sie(run['sie'])}\n```"]
    return "\n\n".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser(description="Reproduce the documented keyword-collision case.")
    ap.add_argument("--source", default="../ml-ai-skills", help="ml-ai-skills git checkout")
    ap.add_argument("--rev", default=HISTORICAL_REV)
    args = ap.parse_args()
    source = Path(args.source).resolve()
    runs = {}
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        tmp = Path(tmp)
        commit = extract_rev(source, args.rev, tmp / "repo")
        hist = tmp / "repo"
        runs["historical"] = {"commit": commit,
                              "n_skills": len(KeywordBaseline(hist, scripts_dir=hist / "scripts").skills),
                              "keyword": keyword_run(hist, hist / "scripts"),
                              "sie": sie_run(hist, tmp / "chroma", build=True)}
        _release_chroma()      # else Windows keeps the temp index's files open and it leaks
    runs["head"] = {"commit": "vendored", "n_skills": len(KeywordBaseline().skills),
                    "keyword": keyword_run(Path("data/skills"), Path("eval/baseline")),
                    "sie": sie_run(Path("data/skills"), Path("data/chroma"), build=False)}
    OUT.mkdir(exist_ok=True)
    (OUT / "collision.json").write_text(json.dumps({"query": QUERY, **runs}, indent=2) + "\n",
                                        encoding="utf-8", newline="\n")
    replace_block(OUT / "RESULTS.md", "collision", render(runs))
    for key in ("historical", "head"):
        r = runs[key]
        print(f"[collision] {key:10s} keyword top-1={_scored_top1(r['keyword']['route']):22s} "
              f"SIE top-1={r['sie']['route'][0]['slug']}")


if __name__ == "__main__":
    main()
