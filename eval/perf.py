"""Router latency and candidate-pool trade-offs on this machine -> benchmarks/PERFORMANCE.md.

Machine-dependent; not byte-reproducible. Latencies depend on the CPU, its load and the
installed library versions, so benchmarks/PERFORMANCE.md and benchmarks/performance.json are
regenerated by hand on an idle machine and never compared by tests or CI. The quality
columns (recall@k, MRR) and candidate counts are deterministic for a given corpus and index.

What is measured:
    pool sweep  hybrid RRF (no cross-encoder) on every `routing` set of the --datasets
                manifest (by default eval/datasets.toml: main + source), using the persisted
                dense index, which is only read, never rebuilt (build it with
                `python -m sie.router --build`): recall@1/3/5, MRR, mean candidates per
                stage, and p50 / p95 / mean latency per stage.
    embedding   the query embedding alone, timed separately on the same queries: the part
                of the `dense` stage that does not depend on the corpus size.
    embedding call  onnx backend: chromadb's `DefaultEmbeddingFunction` (a new ONNX session
                per call; what DenseIndex called before) vs the held `ONNXMiniLM_L6_V2`
                instance DenseIndex uses now, on the same first --compare-queries queries:
                p50 / p95 / mean per call, and whether the vectors are identical.
    reranker    the same as the pool sweep per --rerank-k at the default pool when the
                cross-encoder weights load; otherwise one line saying why it was not measured.
    --scale     latency only: the chunk set replicated N times (copy i's slugs suffixed
                `~i`) into temporary ChromaDB indexes (deleted afterwards) + BM25, routed on
                the first --scale-queries queries. `--scale 1` alone (the default) skips it.

Each configuration gets one untimed warm-up pass, then --repeat timed passes interleaved
across configurations (pool sizes, rerank_k values, scale factors), so drift in machine
speed spreads over all of them. Latencies are the router's own per-stage timings
(`RouteResult.timings_ms`); percentiles are nearest-rank (`eval.metrics.percentile`).
The only wall-clock value written is the `--stamp` date. Cost: queries x (1 + repeat)
route() calls per configuration; each phase prints its call count before it starts.

Usage (from the repo root):
    python -m eval.perf                   # pool sweep 5..80, repeat 3, reranker check, no scaling
    python -m eval.perf --pools 5,10,20,40,80 --repeat 3 --scale 1,4,16 --rerank-k 5,10,20
                                          # the committed run, on an idle machine
    python -m eval.perf --pools 10,20 --repeat 1 --scale 1,2 --out /tmp/perf   # smoke test
"""
