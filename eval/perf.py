# -- query sets ------------------------------------------------------------------------------

def routing_queries(datasets: list[Dataset]) -> list[Query]:
    """Every query of every `routing` dataset, set by set in file order."""
    return [Query(d.name, row["query"], row["gold"])
            for d in datasets if d.kind == "routing" for row in d.rows]


def dataset_facts(datasets: list[Dataset]) -> dict[str, dict]:
    """Name -> path, n and sha256 prefix of each `routing` dataset (report provenance)."""
    return {d.name: {"path": Path(d.path).as_posix(), "n": d.n, "sha256": d.sha256[:12]}
            for d in datasets if d.kind == "routing"}


def _by_set(queries: list[Query]) -> dict[str, list[int]]:
    """Set name -> indexes of its queries, sets in first-seen order."""
    groups: dict[str, list[int]] = {}
    for i, q in enumerate(queries):
        groups.setdefault(q.set_name, []).append(i)
    return groups


# -- aggregation (pure) ----------------------------------------------------------------------

def quality(ranked: list[list[str]], golds: list) -> dict[str, float]:
    """Mean recall@1/3/5 and MRR over paired rankings and golds (rounded to 6 decimals)."""
    if not ranked or len(ranked) != len(golds):
        raise ValueError("quality needs one ranking per gold label, and at least one")
    n = len(ranked)
    out = {f"recall@{k}": sum(recall_at_k(r, g, k) for r, g in zip(ranked, golds)) / n
           for k in RECALL_KS}
    out["mrr"] = sum(reciprocal_rank(r, g) for r, g in zip(ranked, golds)) / n
    return {key: round(value, 6) for key, value in out.items()}


def mean_candidates(results: list[RouteResult]) -> dict[str, float]:
    """Mean candidate count per stage; a result without a stage (e.g. no rerank) counts 0.

    Stages follow CANDIDATES order; stages no result reports are omitted, unknown ones
    follow sorted.
    """
    if not results:
        raise ValueError("mean_candidates needs at least one result")
    present = {key for r in results for key in r.candidates}
    keys = [key for key in CANDIDATES if key in present] + sorted(present - set(CANDIDATES))
    return {key: round(sum(r.candidates.get(key, 0) for r in results) / len(results), 3)
            for key in keys}


def stage_stats(timings: list[dict[str, float]]) -> dict[str, dict[str, float]]:
    """n / p50 / p95 / mean (ms) per stage, over the samples that ran the stage.

    Stages follow STAGES order; stages no sample ran are omitted, unknown ones follow sorted.
    Percentiles are nearest-rank, so they are always observed values.
    """
    present = {stage for t in timings for stage in t}
    out: dict[str, dict[str, float]] = {}
    for stage in [s for s in STAGES if s in present] + sorted(present - set(STAGES)):
        values = [t[stage] for t in timings if stage in t]
        out[stage] = {"n": len(values), "p50": percentile(values, 50), "p95": percentile(values, 95),
                      "mean": round(sum(values) / len(values), 3)}
    return out


# -- measurement -----------------------------------------------------------------------------

def _pass(router: Routable, texts: list[str], setting: Setting, k: int) -> list[RouteResult]:
    return [router.route(q, k=k, pool=setting.pool, rerank_k=setting.rerank_k) for q in texts]


def _ranked(results: list[RouteResult]) -> list[list[str]]:
    return [[s.slug for s in r.results] for r in results]


def measure_arms(arms: list[tuple[Routable, Setting]], queries: list[Query], repeat: int,
                 k: int = DEPTH) -> list[dict]:
    """Quality, candidates and per-stage latency of each (router, setting) arm.

    Every arm first gets one untimed warm-up pass, whose rankings give the quality and
    candidate numbers; then `repeat` timed passes run, interleaved across arms (pass 1 of
    every arm, then pass 2, ...), so drift in machine speed spreads over all of them. A
    timed pass whose rankings differ from the warm-up marks the arm non-deterministic.

    Args:
        arms: (anything with `route(query, k, pool, rerank_k) -> RouteResult`, setting),
            in report order.
        queries: labeled queries (quality is reported per set).
        repeat: timed passes per arm (>= 1).
        k: skills requested per query.

    Returns:
        One dict per arm: pool, rerank_k, samples (= len(queries) * repeat), deterministic,
        reranked (warm-up results the cross-encoder ordered), quality and candidates
        (set -> ...), latency_ms (`stage_stats` of the timed passes).
    """
    if repeat < 1:
        raise ValueError(f"repeat must be >= 1, got {repeat}")
    if not queries or not arms:
        raise ValueError("measuring needs at least one query and one configuration")
    texts = [q.text for q in queries]
    warm = [_pass(router, texts, s, k) for router, s in arms]
    timings: list[list[dict[str, float]]] = [[] for _ in arms]
    stable = [True] * len(arms)
    for _ in range(repeat):
        for i, (router, setting) in enumerate(arms):
            gc.collect()                      # no collector debt from the previous pass
            results = _pass(router, texts, setting, k)
            timings[i].extend(dict(r.timings_ms) for r in results)
            stable[i] = stable[i] and _ranked(results) == _ranked(warm[i])
    groups = _by_set(queries)
    rows = []
    for i, (_, setting) in enumerate(arms):
        ranked = _ranked(warm[i])
        rows.append({
            "pool": setting.pool, "rerank_k": setting.rerank_k, "samples": len(timings[i]),
            "deterministic": stable[i], "reranked": sum(r.reranked for r in warm[i]),
            "quality": {name: {"n": len(idx), **quality([ranked[j] for j in idx],
                                                        [queries[j].gold for j in idx])}
                        for name, idx in groups.items()},
            "candidates": {name: mean_candidates([warm[i][j] for j in idx])
                           for name, idx in groups.items()},
            "latency_ms": stage_stats(timings[i]),
        })
    return rows


def measure(router: Routable, queries: list[Query], settings: list[Setting], repeat: int,
            k: int = DEPTH) -> list[dict]:
    """`measure_arms` for one router under several settings (one row per setting)."""
    return measure_arms([(router, s) for s in settings], queries, repeat, k)


def measure_embedding(embed: Callable[[str], object], queries: list[Query],
                      repeat: int) -> dict[str, float]:
    """Latency (ms) of embedding each query alone: the corpus-size-independent part of `dense`.

    One untimed warm-up pass, then `repeat` timed passes.

    Returns:
        `stage_stats` of the "embed" samples: n, p50, p95, mean.
    """
    if repeat < 1 or not queries:
        raise ValueError("measure_embedding needs repeat >= 1 and at least one query")
    texts = [q.text for q in queries]
    for text in texts:
        embed(text)
    samples = []
    for _ in range(repeat):
        gc.collect()
        for text in texts:
            start = time.perf_counter()
            embed(text)
            samples.append({"embed": round((time.perf_counter() - start) * 1000.0, 3)})
    return stage_stats(samples)["embed"]


def _vector(embed: Callable[[list[str]], object], text: str) -> list[float]:
    return [float(x) for x in list(embed([text]))[0]]


def compare_embedding_calls(before: Callable[[list[str]], object],
                            held: Callable[[list[str]], object], queries: list[Query],
                            repeat: int) -> dict:
    """Per-call latency of two embedding functions on the same queries, and whether they agree.

    Each query is embedded alone. One untimed pass per function gives the vectors that are
    compared; then `repeat` timed passes alternate between the two (before, held, before,
    ...), so drift in machine speed hits both alike.

    Args:
        before: what DenseIndex called before (chromadb's DefaultEmbeddingFunction, which
            builds a new ONNX session on every call).
        held: the embedding function DenseIndex holds now (one ONNXMiniLM_L6_V2 instance).
        queries: labeled queries (only the text is used).
        repeat: timed passes per function (>= 1).

    Returns:
        {"measured": True, "queries": n, "repeat": repeat, "before": stats, "held": stats,
        "identical": every vector equal element for element, "max_abs_diff": largest element
        difference (None when the dimensions differ)}, stats being `stage_stats`
        n / p50 / p95 / mean in ms.
    """
    if repeat < 1 or not queries:
        raise ValueError("compare_embedding_calls needs repeat >= 1 and at least one query")
    texts = [q.text for q in queries]
    identical, max_diff = True, 0.0
    for text in texts:
        a, b = _vector(before, text), _vector(held, text)
        if len(a) != len(b):
            identical, max_diff = False, None
            break
        identical = identical and a == b
        max_diff = max([max_diff] + [abs(x - y) for x, y in zip(a, b)])
    samples: dict[str, list[dict[str, float]]] = {"before": [], "held": []}
    for _ in range(repeat):
        for name, embed in (("before", before), ("held", held)):
            gc.collect()
            for text in texts:
                start = time.perf_counter()
                embed([text])
                samples[name].append({"embed": round((time.perf_counter() - start) * 1000.0, 3)})
    return {"measured": True, "queries": len(texts), "repeat": repeat, "identical": identical,
            "max_abs_diff": max_diff,
            **{name: stage_stats(s)["embed"] for name, s in samples.items()}}


def embedding_call_functions(dense) -> tuple[Callable, Callable]:
    """(chromadb's DefaultEmbeddingFunction, the index's held embedder) for the onnx backend.

    Raises:
        ValueError: the index does not use the onnx embedder (nothing to compare).
    """
    if getattr(dense, "embedder", None) != "onnx":
        raise ValueError(f"the index uses the {getattr(dense, 'embedder', '?')} embedder; the "
                         f"comparison is for the onnx backend")
    from chromadb.utils.embedding_functions import DefaultEmbeddingFunction
    return DefaultEmbeddingFunction(), dense._lazy_embedder()


def measure_embedding_calls(dense, queries: list[Query], repeat: int) -> dict:
    """`compare_embedding_calls` for `dense`'s onnx embedder, or why it was not measured."""
    try:
        before, held = embedding_call_functions(dense)
        return compare_embedding_calls(before, held, queries, repeat)
    except Exception as e:                    # no chromadb, other backend, model fetch failed
        return {"measured": False, "reason": f"{type(e).__name__}: {e}"}


def measure_reranker(make_router: Callable[[], HybridRouter], queries: list[Query],
                     rerank_ks: list[int], pool: int, repeat: int) -> dict:
    """Cross-encoder quality + latency per rerank_k, or why it could not be measured.

    Args:
        make_router: builds a hybrid router with a strict reranker (a failed load raises).
    """
    router = make_router()
    model = getattr(router.reranker, "model_name", None)
    try:
        router.warm_up()
    except RerankerUnavailable as e:
        return {"measured": False, "reason": str(e), "model": model, "pool": pool}
    rows = measure(router, queries, [Setting(pool, rk) for rk in rerank_ks], repeat)
    return {"measured": True, "model": model, "pool": pool, "rows": rows}


# -- synthetic scaling -----------------------------------------------------------------------

def replicate_chunks(chunks: list[Chunk], factor: int) -> list[Chunk]:
    """The chunk set `factor` times: copy 1 unchanged, copy i (2..factor) with slug `<slug>~i`.

    Texts and sections are kept; chunk ids swap in the new slug (`a::Card::0` ->
    `a~2::Card::0`), or get `~i` appended when they don't start with `<slug>::`. `~` is not
    a valid slug character, so synthetic slugs never collide with real ones.

    Raises:
        ValueError: factor < 1, or the replicated chunk ids are not unique.
    """
    if isinstance(factor, bool) or not isinstance(factor, int) or factor < 1:
        raise ValueError(f"factor must be an integer >= 1, got {factor!r}")
    out = list(chunks)
    for i in range(2, factor + 1):
        for c in chunks:
            slug, prefix = f"{c.skill_slug}~{i}", f"{c.skill_slug}::"
            chunk_id = (slug + c.chunk_id[len(c.skill_slug):] if c.chunk_id.startswith(prefix)
                        else f"{c.chunk_id}~{i}")
            out.append(Chunk(skill_slug=slug, section=c.section, text=c.text, chunk_id=chunk_id))
    if len({c.chunk_id for c in out}) != len(out):
        raise ValueError("replicated chunk ids are not unique")
    return out


class DedupDenseIndex(DenseIndex):
    """DenseIndex that embeds each distinct text once per call.

    Replicated corpora repeat every text `factor` times; identical texts get identical
    vectors, so building embeds only the distinct ones. Nothing is cached across calls:
    every query is embedded afresh, so query latency is unchanged.
    """

    def _embed(self, texts: list[str]) -> list[list[float]]:
        unique = list(dict.fromkeys(texts))
        by_text = dict(zip(unique, super()._embed(unique)))
        return [by_text[t] for t in texts]


class ChunkRouter(HybridRouter):
    """HybridRouter over a given chunk list instead of a corpus directory (latency runs only)."""

    def __init__(self, chunks: list[Chunk], persist_dir: str, mode: str = "hybrid"):
        super().__init__(skills_dir="(synthetic)", use_reranker=False, mode=mode,
                         persist_dir=persist_dir)
        self.dense = DedupDenseIndex(persist_dir=persist_dir)
        self._given = list(chunks)

    def _load_chunks_locked(self) -> list[Chunk]:
        if self._chunks is None:
            texts = {c.chunk_id: c.text for c in self._given}
            if not texts or len(texts) != len(self._given):
                raise RuntimeError("synthetic chunk list is empty or has duplicate chunk ids")
            self._texts = texts
            self._chunks = self._given
        return self._chunks


def _scale_router(chunks: list[Chunk], persist_dir: Path) -> ChunkRouter:
    return ChunkRouter(chunks, persist_dir=str(persist_dir))


def _release_handles() -> None:
    """Close chromadb's cached clients so a temporary index's files can be deleted (Windows)."""
    if "chromadb" in sys.modules:           # never imported -> nothing is open
        from eval.collision import _release_chroma
        _release_chroma()


def measure_scale(chunks: list[Chunk], factors: list[int], queries: list[Query], repeat: int,
                  workdir: Path, pool: int,
                  make_router: Callable[[list[Chunk], Path], HybridRouter] | None = None) -> list[dict]:
    """Per-stage latency of a router over the chunk set replicated `factor` times.

    Every factor's index is built first (under `workdir/scale-<factor>`), then all of them
    are timed together with `measure_arms`, passes interleaved across factors, so drift in
    machine speed is not mistaken for a scaling effect. A factor whose build fails (e.g. the
    vector store rejects the batch) is recorded with its error and the rest still run.
    Quality is not reported: every answer has `factor` identical copies.

    Args:
        make_router: (chunks, persist_dir) -> unbuilt router (default: `ChunkRouter`).
    """
    make_router = make_router or _scale_router
    rows: list[dict] = []
    built: list[tuple[HybridRouter, dict]] = []
    try:
        for factor in factors:
            replicated = replicate_chunks(chunks, factor)
            row: dict = {"factor": factor, "chunks": len(replicated),
                         "skills": len({c.skill_slug for c in replicated})}
            rows.append(row)
            try:
                router = make_router(replicated, workdir / f"scale-{factor}")
                row["ef_search"] = getattr(router.dense, "ef_search", None)
                router.build()
                router.warm_up()
            except Exception as e:            # record and go on: the report shows the error
                row["error"] = f"{type(e).__name__}: {e}"
                print(f"[perf] scale {factor}: not measured: {row['error']}", file=sys.stderr)
                continue
            built.append((router, row))
        router = None
        if built:
            measured = measure_arms([(r, Setting(pool)) for r, _ in built], queries, repeat)
            for row, m in zip([row for _, row in built], measured):   # no loop var keeps a router
                row.update(samples=m["samples"], deterministic=m["deterministic"],
                           latency_ms=m["latency_ms"])
    finally:
        router = None                         # drop every router before closing their clients,
        built.clear()                         # else their index files stay open (Windows)
        _release_handles()
    return rows


def run_scale(chunks: list[Chunk], factors: list[int], queries: list[Query], repeat: int,
              pool: int) -> dict:
    """`measure_scale` in a temporary directory that is removed afterwards (checked)."""
    with tempfile.TemporaryDirectory(prefix="sie-perf-", ignore_cleanup_errors=True) as tmp:
        rows = measure_scale(chunks, factors, queries, repeat, Path(tmp), pool)
    removed = not Path(tmp).exists()
    if not removed:
        print(f"[perf] WARNING: could not remove the temporary index at {tmp}", file=sys.stderr)
    return {"queries": len(queries), "pool": pool, "k": DEPTH, "rows": rows,
            "temp_dir_removed": removed}


# -- rendering (pure) ------------------------------------------------------------------------

def fmt_ms(value: float) -> str:
    """Milliseconds to about 3 significant digits (noise dominates beyond): 0.042, 1.23, 12.3, 123."""
    if value >= 100:
        return f"{value:.0f}"
    if value >= 10:
        return f"{value:.1f}"
    if value >= 1:
        return f"{value:.2f}"
    return f"{value:.3f}"


def fmt_latency(stats: dict | None) -> str:
    """`p50 / p95 / mean` of one stage, or `-` when the stage did not run."""
    if not stats:
        return "-"
    return " / ".join(fmt_ms(stats[key]) for key in ("p50", "p95", "mean"))


def _stages(rows: list[dict]) -> list[str]:
    """STAGES that some row measured, in STAGES order."""
    present = {stage for r in rows for stage in r.get("latency_ms", {})}
    return [s for s in STAGES if s in present]


def _label(value: int, default: int | None) -> str:
    return f"{value} (default)" if value == default else str(value)


def quality_table(rows: list[dict], key: str, default: int | None = None) -> str:
    """One line per (setting, set): n, recall@1/3/5, MRR and mean candidates per stage."""
    stages = [c for c in CANDIDATES if any(c in cand for r in rows for cand in r["candidates"].values())]
    header = [key, "set", "n", *(f"recall@{k}" for k in RECALL_KS), "MRR",
              *(CANDIDATES[c] for c in stages)]
    body = []
    for r in rows:
        for name, q in sorted(r["quality"].items()):
            cand = r["candidates"][name]
            body.append([_label(r[key], default), name, str(q["n"]),
                         *(f"{q[f'recall@{k}']:.3f}" for k in RECALL_KS), f"{q['mrr']:.3f}",
                         *(f"{cand.get(c, 0):.1f}" for c in stages)])
    return md_table(header, body)


def latency_table(rows: list[dict], key: str, default: int | None = None) -> str:
    """One line per setting: samples and `p50 / p95 / mean` ms per stage."""
    stages = _stages(rows)
    body = [[_label(r[key], default), str(r["samples"])]
            + [fmt_latency(r["latency_ms"].get(s)) for s in stages] for r in rows]
    return md_table([key, "n", *stages], body)


def scale_table(rows: list[dict]) -> str:
    """One line per measured scale factor: corpus size, samples, `p50 / p95 / mean` per stage."""
    ok = [r for r in rows if "error" not in r]
    stages = _stages(ok)
    body = [[f"{r['factor']}x", str(r["chunks"]), str(r["skills"]), str(r["samples"])]
            + [fmt_latency(r["latency_ms"].get(s)) for s in stages] for r in ok]
    return md_table(["scale", "chunks", "skills", "n", *stages], body)


def _nondeterministic(rows: list[dict], key: str) -> str:
    bad = [str(r[key]) for r in rows if not r["deterministic"]]
    return ("Rankings were identical in the warm-up and every timed pass." if not bad else
            f"**Rankings changed between passes for {key} {', '.join(bad)}** (quality is from "
            f"the warm-up pass).")


def _setup(report: dict) -> str:
    env, setup = report["environment"], report["setup"]
    versions = ", ".join(f"{name} {v}" for name, v in sorted(env["versions"].items()))
    corpus, dense = setup["corpus"], setup["dense"]
    ident = corpus["name"] + (f"@{corpus['version']}" if corpus["version"] else "")
    sets = ", ".join(f"`{name}` = `{s['path']}` (n={s['n']}, sha256 `{s['sha256']}`)"
                     for name, s in sorted(setup["queries"].items()))
    count = f"; {dense['count']} vectors" if dense.get("count") is not None else ""
    passes = f"{setup['repeat']} timed pass" + ("" if setup["repeat"] == 1 else "es")
    return "\n".join([
        f"- date: {report['stamp']} (UTC, `--stamp`; the only wall-clock value in this file)",
        f"- machine: {env['platform']}; {env['processor']}; {env['cpu_count']} logical CPUs",
        f"- software: Python {env['python']}, {versions}",
        f"- corpus: `{ident}`: {corpus['n_skills']} skills, {corpus['n_chunks']} chunks (content "
        f"fingerprint `{corpus['content_fingerprint']}`, chunk fingerprint `{corpus['chunk_fingerprint']}`)",
        f"- dense index: `{dense['persist_dir']}` (read, never rebuilt{count}), `{dense['model']}` "
        f"via the `{dense['embedder']}` embedder",
        f"- queries: {sets}",
        f"- method: `route(query, k={setup['k']})`, RRF k={setup['rrf_k']}. Every configuration "
        f"gets one untimed warm-up pass, then {passes} interleaved across configurations, "
        f"so n = queries x {setup['repeat']}. Latency is the router's own "
        f"per-stage `time.perf_counter()` timing (`RouteResult.timings_ms`); p50/p95 are "
        f"nearest-rank. Cells read **p50 / p95 / mean** in ms; `total` is the whole call "
        f"(at least the sum of its stages).",
    ])


def _embedding_line(embedding: dict) -> str:
    return (f"Query embedding alone, timed separately on the same queries (n={embedding['n']}): "
            f"**{fmt_latency(embedding)}** ms (p50 / p95 / mean). That part of `dense` does not "
            f"grow with the corpus; the rest of `dense` is the vector-store query and its results.")


def _embedding_calls_section(calls: dict) -> str:
    """Before/after rows of the query-embedding call (onnx backend)."""
    if not calls["measured"]:
        return f"not measured: {calls['reason']}"
    passes = calls["repeat"]
    same = "yes" if calls["identical"] else "no"
    diff = ("dimensions differ" if calls["max_abs_diff"] is None
            else f"largest element difference {calls['max_abs_diff']:.3g}")
    rows = [["before this change: chromadb `DefaultEmbeddingFunction()` (builds a new ONNX "
             "session on every call)", str(calls["before"]["n"]), fmt_latency(calls["before"])],
            ["now: one held `ONNXMiniLM_L6_V2` instance (what `DenseIndex` calls)",
             str(calls["held"]["n"]), fmt_latency(calls["held"])]]
    return "\n\n".join([
        f"**Embedding call comparison, one query per call.** The same {calls['queries']} "
        f"queries (the first {calls['queries']} of the pool sweep's) embedded by what "
        f"`DenseIndex` called before and by what it holds now; one untimed pass each, then {passes} timed "
        f"pass{'' if passes == 1 else 'es'} alternating between the two. Machine-dependent "
        f"like everything here.",
        md_table(["embedding call", "n", "p50 / p95 / mean (ms)"], rows),
        f"Vectors identical on all {calls['queries']} queries: **{same}** ({diff}).",
    ])


def _reranker_section(rr: dict) -> str:
    if not rr["measured"]:
        return f"not measured: {rr['reason']}"
    rows, pool = rr["rows"], rr["pool"]
    model = f" `{rr['model']}`" if rr.get("model") else ""
    return "\n\n".join([
        f"Cross-encoder{model} over the hybrid candidates at pool {pool}; `rerank_k` = top fused "
        f"skills whose retrieved chunks are cross-encoded (the default is the pool, {pool}).",
        quality_table(rows, "rerank_k", default=pool),
        latency_table(rows, "rerank_k", default=pool),
        _nondeterministic(rows, "rerank_k"),
    ])


def _scale_section(scale: dict | None) -> str:
    if scale is None:
        return "not run (pass e.g. `--scale 1,4,16`)."
    ok = [r for r in scale["rows"] if "error" not in r]
    failed = [r for r in scale["rows"] if "error" in r]
    efs = sorted({r["ef_search"] for r in scale["rows"] if r.get("ef_search") is not None})
    hnsw = (f" (HNSW ef_search={efs[0]}; once an index holds more chunks than that, the "
            f"search is approximate)") if len(efs) == 1 else ""
    parts = [
        f"**Latency only.** The chunk set is replicated N times (copy i's slugs suffixed `~i`) "
        f"and indexed into a temporary ChromaDB directory{hnsw} plus a fresh BM25 index; "
        f"identical texts are embedded once, since their vectors are the same. "
        f"`route(query, k={scale['k']}, pool={scale['pool']})` (hybrid RRF, no cross-encoder) is "
        f"timed on the first {scale['queries']} queries, passes interleaved across scales. "
        f"`dense` includes the query embedding, which does not depend on the corpus size. "
        f"Every answer has N identical copies, so **quality on these duplicated corpora is not "
        f"meaningful** and is not reported. These numbers describe this machine only.",
        scale_table(scale["rows"]),
    ]
    if failed:
        parts.append("\n".join(f"- {r['factor']}x ({r['chunks']} chunks): not measured: {r['error']}"
                               for r in failed))
    if ok:
        parts.append(_nondeterministic([{**r, "scale": f"{r['factor']}x"} for r in ok], "scale"))
    if not scale["temp_dir_removed"]:
        parts.append("**Warning:** the temporary index directory could not be removed.")
    return "\n\n".join(parts)


def render(report: dict) -> str:
    """benchmarks/PERFORMANCE.md from a `performance.json` report.

    A pure function of the report that never depends on dict order (maps are rendered
    sorted, stages in STAGES order), so re-rendering the saved JSON reproduces the file.
    """
    default_pool = report["setup"]["default_pool"]
    pools = report["pools"]
    calls = report.get("embedding_calls")          # absent in reports written before it existed
    return "\n\n".join([
        "# Router performance",
        f"_Generated by `{report['command']}`; do not edit by hand. **{NOTE.capitalize()}:** "
        f"latencies are this machine's under its load at the time. Quality and candidate "
        f"counts are deterministic for this corpus and index._",
        _setup(report),
        "## Candidate pool sweep: hybrid RRF, no cross-encoder",
        f"`pool` = chunks taken from each retriever before fusion; {default_pool} is the "
        f"default and the benchmarked setting in [RESULTS.md](RESULTS.md).",
        quality_table(pools, "pool", default_pool),
        latency_table(pools, "pool", default_pool),
        _nondeterministic(pools, "pool"),
        _embedding_line(report["embedding"]),
        *([_embedding_calls_section(calls)] if calls is not None else []),
        "## Cross-encoder reranker",
        _reranker_section(report["reranker"]),
        "## Synthetic corpus scaling",
        _scale_section(report["scale"]),
    ]) + "\n"


# -- environment + CLI -----------------------------------------------------------------------

def _version(package: str) -> str:
    try:
        return md.version(package)
    except md.PackageNotFoundError:
        return "not installed"


def environment() -> dict:
    """Platform, CPU and library versions (never imports the libraries themselves)."""
    return {"platform": platform.platform(), "processor": platform.processor() or platform.machine(),
            "cpu_count": os.cpu_count(), "python": platform.python_version(),
            "versions": {name: _version(name) for name in VERSIONED}}


def int_list(text: str) -> list[int]:
    """argparse type: "20,5,20" -> [5, 20] (sorted, deduplicated, each >= 1)."""
    try:
        values = [int(part) for part in text.split(",") if part.strip()]
    except ValueError:
        raise argparse.ArgumentTypeError(f"expected comma-separated integers, got {text!r}") from None
    if not values or min(values) < 1:
        raise argparse.ArgumentTypeError(f"expected integers >= 1, got {text!r}")
    return sorted(set(values))


def positive_int(text: str) -> int:
    """argparse type: an integer >= 1."""
    try:
        value = int(text)
    except ValueError:
        raise argparse.ArgumentTypeError(f"expected an integer, got {text!r}") from None
    if value < 1:
        raise argparse.ArgumentTypeError(f"expected an integer >= 1, got {text!r}")
    return value


def iso_date(text: str) -> str:
    """argparse type: a YYYY-MM-DD date."""
    try:
        return date.fromisoformat(text).isoformat()
    except ValueError:
        raise argparse.ArgumentTypeError(f"expected a YYYY-MM-DD date, got {text!r}") from None


def _csv(values: list[int]) -> str:
    return ",".join(map(str, values))


def command_line(args: argparse.Namespace) -> str:
    """The canonical command that reproduces this run's configuration (every knob spelled out)."""
    parts = ["python -m eval.perf", f"--pools {_csv(args.pools)}", f"--repeat {args.repeat}",
             f"--scale {_csv(args.scale)}", f"--rerank-k {_csv(args.rerank_k)}"]
    if args.scale_queries != SCALE_QUERIES:
        parts.append(f"--scale-queries {args.scale_queries}")
    if args.compare_queries != COMPARE_QUERIES:
        parts.append(f"--compare-queries {args.compare_queries}")
    for flag, value, default in (("--datasets", Path(args.datasets).as_posix(),
                                  DEFAULT_MANIFEST.as_posix()),
                                 ("--skills", args.skills, DEFAULT_SKILLS),
                                 ("--manifest", args.manifest, None),
                                 ("--persist-dir", args.persist_dir, DEFAULT_PERSIST),
                                 ("--reranker", args.reranker, None)):
        if value != default:
            parts.append(f"{flag} {value}")
    return " ".join(parts)


def _setup_facts(router: HybridRouter, chunks: list[Chunk], datasets: list[Dataset],
                 args: argparse.Namespace) -> dict:
    corpus = router.corpus
    info = router.status()["dense"].get("index") or {}
    return {
        "corpus": {"name": corpus.name if corpus else "", "version": corpus.version if corpus else "",
                   "n_skills": len(router.skills), "n_chunks": len(chunks),
                   "content_fingerprint": corpus.fingerprint if corpus else "",
                   "chunk_fingerprint": corpus_fingerprint(chunks)},
        "dense": {"persist_dir": Path(args.persist_dir).as_posix(), "embedder": router.dense.embedder,
                  "model": router.dense.model_name, "count": info.get("count")},
        "queries": dataset_facts(datasets),
        "k": DEPTH, "repeat": args.repeat, "rrf_k": router.config.rrf_k,
        "default_pool": RetrievalConfig().candidate_pool,
    }


def _load_queries(router: HybridRouter, manifest: Path) -> tuple[list[Dataset], list[Query]]:
    """The manifest's datasets for the router's (loaded) corpus, and their routing queries."""
    corpus = router.corpus
    try:
        datasets, skipped = load_datasets(manifest, slugs=set(router.skills),
                                          corpus_name=corpus.name if corpus else None)
    except (OSError, ValueError) as e:
        sys.exit(f"[perf] {manifest}: {e}")
    for reason in skipped:
        _log(reason)
    queries = routing_queries(datasets)
    if not queries:
        sys.exit(f"[perf] {manifest} has no routing dataset for corpus "
                 f"'{corpus.name if corpus else '?'}'")
    return datasets, queries


def _summary(rows: list[dict], key: str) -> None:
    for r in rows:
        q = " ".join(f"{name} r@1={v['recall@1']:.3f} mrr={v['mrr']:.3f}" for name, v in r["quality"].items())
        total = r["latency_ms"].get("total")
        _log(f"{key}={r[key]:<3d} {q} | total {fmt_latency(total)} ms (n={r['samples']})")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        description="Router latency / candidate-pool trade-offs on this machine (machine-dependent).")
    ap.add_argument("--pools", type=int_list, default=list(DEFAULT_POOLS), metavar="N,N",
                    help=f"candidate pools to sweep (default {_csv(DEFAULT_POOLS)})")
    ap.add_argument("--repeat", type=positive_int, default=DEFAULT_REPEAT,
                    help="timed passes per configuration after one warm-up pass")
    ap.add_argument("--scale", type=int_list, default=[1], metavar="N,N",
                    help="synthetic corpus replication factors, latency only (default 1 = skip)")
    ap.add_argument("--scale-queries", type=positive_int, default=SCALE_QUERIES, metavar="N",
                    help="queries timed per scale factor")
    ap.add_argument("--compare-queries", type=positive_int, default=COMPARE_QUERIES, metavar="N",
                    help="queries for the embedding-call comparison (old per-call ONNX session "
                         "vs the held instance)")
    ap.add_argument("--rerank-k", type=int_list, default=list(DEFAULT_RERANK_KS), metavar="N,N",
                    help="rerank_k values to measure when the cross-encoder loads")
    ap.add_argument("--reranker", metavar="MODEL", help="cross-encoder id or local dir")
    ap.add_argument("--datasets", type=Path, default=DEFAULT_MANIFEST, metavar="PATH",
                    help=f"query-set manifest; every `routing` set is timed "
                         f"(default {DEFAULT_MANIFEST.as_posix()})")
    ap.add_argument("--skills", default=DEFAULT_SKILLS)
    ap.add_argument("--manifest", metavar="PATH", help="corpus.toml (default <skills>/corpus.toml)")
    ap.add_argument("--persist-dir", default=DEFAULT_PERSIST,
                    help="persisted dense index; read only, never rebuilt")
    ap.add_argument("--out", type=Path, default=OUT, help="output directory (default benchmarks)")
    ap.add_argument("--stamp", type=iso_date, default=None,
                    help="date for the header (default: today, UTC)")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")
    stamp = args.stamp or datetime.now(timezone.utc).date().isoformat()

    router = HybridRouter(skills_dir=args.skills, use_reranker=False, persist_dir=args.persist_dir,
                          manifest=args.manifest)
    try:
        router.warm_up()                      # corpus + BM25 + index freshness + embedder
    except RuntimeError as e:
        sys.exit(f"[perf] {e}")
    chunks = router._load_chunks()
    datasets, queries = _load_queries(router, args.datasets)

    start = time.perf_counter()
    passes = 1 + args.repeat
    _log(f"pool sweep {_csv(args.pools)} over {len(queries)} queries, repeat {args.repeat} "
         f"({len(queries) * passes * len(args.pools)} route() calls) ...")
    pools = measure(router, queries, [Setting(p) for p in args.pools], args.repeat)
    _summary(pools, "pool")
    _log(f"query embedding alone ({len(queries) * passes} calls) ...")
    embedding = measure_embedding(lambda q: router.dense._embed([q]), queries, args.repeat)
    _log(f"embed {fmt_latency(embedding)} ms (n={embedding['n']})")
    compared = queries[:args.compare_queries]
    _log(f"embedding call, before vs held ({len(compared) * passes * 2} calls) ...")
    embedding_calls = measure_embedding_calls(router.dense, compared, args.repeat)
    _log("embedding call: " + (
        f"before {fmt_latency(embedding_calls['before'])} ms, held "
        f"{fmt_latency(embedding_calls['held'])} ms, identical: "
        f"{'yes' if embedding_calls['identical'] else 'no'}" if embedding_calls["measured"]
        else f"not measured: {embedding_calls['reason']}"))
    default_pool = RetrievalConfig().candidate_pool
    _log(f"reranker check (pool {default_pool}, rerank_k {_csv(args.rerank_k)}) ...")
    reranker = measure_reranker(
        lambda: HybridRouter(skills_dir=args.skills, use_reranker=True, strict_rerank=True,
                             persist_dir=args.persist_dir, manifest=args.manifest,
                             reranker_model=args.reranker),
        queries, args.rerank_k, default_pool, args.repeat)
    if reranker["measured"]:
        _summary(reranker["rows"], "rerank_k")
    else:
        _log(f"reranker not measured: {reranker['reason']}")
    scale = None
    if any(f > 1 for f in args.scale):
        n_scale = min(args.scale_queries, len(queries))
        _log(f"synthetic scaling {_csv(args.scale)} on {n_scale} queries "
             f"({n_scale * passes * len(args.scale)} route() calls) ...")
        scale = run_scale(chunks, args.scale, queries[:args.scale_queries], args.repeat, default_pool)
        for r in scale["rows"]:
            _log(f"scale {r['factor']}x ({r['chunks']} chunks): "
                 + (f"not measured: {r['error']}" if "error" in r else
                    f"total {fmt_latency(r['latency_ms'].get('total'))} ms (n={r['samples']})"))

    report = {"command": command_line(args), "note": NOTE, "stamp": stamp,
              "environment": environment(), "setup": _setup_facts(router, chunks, datasets, args),
              "pools": pools, "embedding": embedding, "embedding_calls": embedding_calls,
              "reranker": reranker, "scale": scale}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "performance.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n",
                                               encoding="utf-8", newline="\n")
    (args.out / "PERFORMANCE.md").write_text(render(report), encoding="utf-8", newline="\n")
    _log(f"wrote {args.out / 'PERFORMANCE.md'}, {args.out / 'performance.json'} "
         f"({time.perf_counter() - start:.0f} s)")


if __name__ == "__main__":
    main()
