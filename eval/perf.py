class Routable(Protocol):
    def route(self, query: str, k: int | None = None, pool: int | None = None,
              rerank_k: int | None = None) -> RouteResult: ...


@dataclass(frozen=True)
class Query:
    """One labeled query; `gold` is a slug or a list of acceptable slugs (eval.metrics)."""
    set_name: str
    text: str
    gold: str | list[str]


@dataclass(frozen=True)
class Setting:
    """One measured configuration: chunks per retriever, and top fused skills cross-encoded."""
    pool: int
    rerank_k: int | None = None


